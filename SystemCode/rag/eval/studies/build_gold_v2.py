"""Merge data/eval/gold_extra_labels.yaml into gold_queries.yaml -> gold_queries_v2.yaml.

The extra rules (source / heading patterns, never chunk ids) came from reviewing unlabeled
top-10 hits by reading title + snippet AFTER seeing retriever output, so v2 is a draft with mild
circularity; it still needs human review. The original file is left untouched.
  uv run python -m rag.eval.studies.build_gold_v2
"""

from __future__ import annotations

import copy
import os
import tempfile

import yaml

from rag.eval.gold import load_gold
from rag.retrieval.retriever import Retriever

from .common import EVAL_DIR, live_chunks

HEADER = (
    "# GENERATED by rag/eval/studies/build_gold_v2.py (gold_queries + gold_extra_labels).\n"
    "# DRAFT -- needs human review. Edit the two source files, not this one.\n"
)


def _resolve(doc: dict, chunks: list[dict]) -> dict[str, set[str]]:
    from rag.eval.gold import resolve_gold

    with tempfile.NamedTemporaryFile("w", suffix=".yaml", delete=False) as f:
        yaml.safe_dump(doc, f, allow_unicode=True)
    try:
        return resolve_gold(load_gold(f.name), chunks)
    finally:
        os.unlink(f.name)


def main() -> None:
    src = yaml.safe_load((EVAL_DIR / "gold_queries.yaml").read_text(encoding="utf-8"))
    extra = yaml.safe_load((EVAL_DIR / "gold_extra_labels.yaml").read_text(encoding="utf-8"))
    r = Retriever(check_model=False)
    chunks = live_chunks(r)
    r.close()
    before = _resolve(src, chunks)
    v2 = copy.deepcopy(src)
    v2["status"] = "draft v2 -- original rules + extra rules from reviewing unlabeled top-10 hits"
    for q in v2["queries"]:
        q["relevant"] = q["relevant"] + extra.get(q["id"], [])
    after = _resolve(v2, chunks)
    body = yaml.safe_dump(v2, sort_keys=False, allow_unicode=True, width=200)
    (EVAL_DIR / "gold_queries_v2.yaml").write_text(HEADER + body, encoding="utf-8")
    for q in v2["queries"]:
        if q["id"] in extra:
            print(q["id"], len(before[q["id"]]), "->", len(after[q["id"]]))


if __name__ == "__main__":
    main()
